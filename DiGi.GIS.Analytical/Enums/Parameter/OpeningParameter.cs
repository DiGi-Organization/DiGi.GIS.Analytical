using DiGi.Analytical.Building.Classes;
using DiGi.Core.Parameter.Classes;
using System.ComponentModel;

namespace DiGi.GIS.Analytical.Enums
{
    /// <summary>
    /// Defines the parameters <c>Modify.GenerateOpenings</c> sets on every window and door it generates, so a run can be traced and redone when a better year built arrives (DiGi-Organization/DiGi.GIS.Analytical#2).
    /// </summary>
    [AssociatedTypes(typeof(Window), typeof(Door)), Description("Opening Parameters")]
    public enum OpeningParameter
    {
        /// <summary>
        /// Gets the building regulation regime the opening was generated under, as a <c>BuildingRegulation</c> name.
        /// </summary>
        [ParameterProperties("2e600cb0-04a4-4406-adf0-b6c6083ed888", "Building regulation", "Building regulation regime the opening was generated under", Core.Parameter.Enums.AccessType.Read), StringParameterValue()] BuildingRegulation,

        /// <summary>
        /// Gets where the year built that selected the regime came from, as a <see cref="GIS.Enums.YearBuiltSource"/> name, or "None" when no year was known.
        /// </summary>
        [ParameterProperties("23be07da-0a8d-4d0b-ac08-d57690ab7de7", "Year built source", "Source of the year built that selected the regime", Core.Parameter.Enums.AccessType.Read), StringParameterValue()] YearBuiltSource,

        /// <summary>
        /// Gets the construction flavour the opening's thermal values were copied from, as a <c>ConstructionFlavour</c> name.
        /// </summary>
        [ParameterProperties("bea98a94-0fc6-4791-89f5-657a518e360e", "Construction flavour", "Construction flavour the thermal values were copied from", Core.Parameter.Enums.AccessType.Read), StringParameterValue()] ConstructionFlavour,

        /// <summary>
        /// Gets the kind of opening, as an <c>OpeningKind</c> name.
        /// </summary>
        [ParameterProperties("3be5a320-9670-4803-bb7b-3681aa6e7ed8", "Opening kind", "Kind of opening", Core.Parameter.Enums.AccessType.Read), StringParameterValue()] OpeningKind,

        /// <summary>
        /// Gets the room use the opening's size was chosen for, as a <c>RoomUse</c> name.
        /// </summary>
        [ParameterProperties("e7fbe37d-bdae-40bd-b1c9-080089a19a0b", "Room use", "Room use the size was chosen for", Core.Parameter.Enums.AccessType.Read), StringParameterValue()] RoomUse,

        /// <summary>
        /// Gets the method that generated the opening.
        /// </summary>
        [ParameterProperties("a9958b11-99a0-4b2b-bd9a-0548ee68cf78", "Generated by", "Method that generated the opening", Core.Parameter.Enums.AccessType.Read), StringParameterValue()] GeneratedBy,
    }
}
